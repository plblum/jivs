import { IJivsDomServices } from './JivsDomServices';
import type { IFieldValueHost } from '@plblum/jivs-engine/build/Interfaces/FieldValueHost';
import type { IssueFound } from '@plblum/jivs-engine/build/Interfaces/Validation';
import type { IValueHostsManager } from '@plblum/jivs-engine/build/Interfaces/ValueHostsManager';

/**
 * PopupErrorMessageDisplayPresentation uses this interface to define the content within its outer element.
 * There are several parts to PopupErrorMessageDisplayPresentation:
 * - The outer element that contains the error indicator content.
 * - ErrorIndicator element that visually represents the presence of an error,
 *   generated by this interface implementation.
 * - The popup element that displays detailed error messages,
 *   generated by a PopupMechanism with content from IMessageFrame.
 * 
 * ```html
 * <div class='jivs-popuperrormessagedisplaypresentation'>
 *     <div class='jivs-errorindicatorcontent'>
 *      <!-- Error indicator content goes here -->
 *     </div>
 * </div>
 * ```
 * 
 */
export interface IErrorIndicatorContent
{
    /**
     * Sets the DOM services instance to be used for rendering and formatting issues.
     * Expected to be established before using apply().
     */    
    setDomServices(domServices: IJivsDomServices): void;
    /**
     * Builds and replaces the content within the specified element.
     * Does not modify the CSS classes on element itself. Its own
     * content should be in a container element with its own CSS classes for styling and layout.
     * @param containerElement The container element where the error indicator content should be rendered.
     * @param issuesFound The list of issues found for the field. Used primarily to 
     * support the {Count} token.
     * @param valueHostsManager The manager for value hosts, used for resolving dynamic values in the content.
     * @param fieldValueHost The host object for the field value, if applicable.
     * Used primarily to resolve the {Label} token if applicable.
     */
    apply(containerElement: HTMLElement, issuesFound: IssueFound[],
        valueHostsManager: IValueHostsManager,
        fieldValueHost: IFieldValueHost | null): void;    
}