// Example: Introduce a new Data Type Lookup Key for Email Address.
// This data type is based on a string but has a specific pattern.
// 1. Need to declare a new Data Type Lookup Key. It will be used
//    within the following code and assigned to the dataType property
//    on the FieldValueHostConfig (the object that describes
//    a single input value from your UI.)
// 2. Implement a Condition class that uses a regular expression.
//    We'll just subclass RegExpCondition itself and have it configure
//    the regular expression. Set its category property to DataTypeCheck.
// 3. Implement IDataTypeCheckGenerator to auto generate our new Condition class
//    when Jivs needs a Data Type Check Condition for the Lookup Key we've created.
// 4. Extend the fluent syntax by subclassing our standard ValidatorBuilder
//    and ConditionBuilder.
// 5. Register new classes with the ValidationServices object in createValidationServices.
//    - Condition class in the ValidationServices.conditionFactory
//    - IDataTypeCheckGenerator subclass in ValidationServices.autoGenerateDataTypeCheckService
//    - ValidatorBuilder and ConditionBuilder subclasses in 
//      ValidationServices.fluentFactory.
// 6. Write unit tests. See the companion file in the Tests folder.


export const EmailAddressLookupKey = 'EmailAddress';
export const EmailAddressConditionType = 'EmailAddressRegExp';  // this can be anything so long as its different from other ConditionTypes

export interface EmailAddressConditionConfig extends RegExpConditionConfig { };

// The Condition that will be used by the DataTypeCheckValidator
// when its dataType property is 'EmailAddress'
// It must still be registered in the ValidationServices.conditionFactory.
export class EmailAddressCondition extends RegExpCondition
{
    constructor(config: EmailAddressConditionConfig)
    {
        super({ ...config, expression: /^([\w\.!#\$%\-+.'_]+@[A-Za-z0-9\-]+(\.[A-Za-z0-9\-]{2,})+)/i });
    }
    public get conditionType(): string {
        return EmailAddressConditionType; 
    }
    public get category(): ConditionCategory {
        return ConditionCategory.DataTypeCheck;
    }
}

// The IDataTypeCheckGenerator implementation that will be used by
// the AutoGenerateDataTypeCheckService to connect the DataTypeCheckValidator
// to the EmailAddressCondition when the dataType property is 'EmailAddress'
// It must still be registered in the ValidationServices.autoGenerateDataTypeCheckService.
export class EmailAddressDataTypeCheckGenerator implements IDataTypeCheckGenerator
{
    public supportsValue(dataTypeLookupKey: string): boolean {
        return dataTypeLookupKey.toLowerCase() === EmailAddressLookupKey.toLowerCase();
    }
    public createConditions(valueHost: IFieldValueHost, dataTypeLookupKey: string, conditionFactory: IConditionFactory): Array<ICondition> {
        let config: EmailAddressConditionConfig = {
            conditionType: EmailAddressConditionType,
            valueHostName: valueHost.getName()
        };
        return [
            new EmailAddressCondition(config)   // or use the conditionFactory, so long as your condition is registered
        ];
    }
}


//#region fluent syntax

// Fluent: Subclass ConditionBuilder and add your condition functions.
export class EmailAddressConditionBuilder
    extends ConditionBuilder<ConditionConfig>
{

    public emailAddress(): void {
        let config: Partial<EmailAddressConditionConfig> =
        {
            conditionType: EmailAddressConditionType
        };
        this.setConfig(config as any);
    }
}

// Fluent: Subclass ValidatorBuilder and add your validator functions. This requires 2 overloads.

export class EmailAddressValidatorBuilder
    extends ValidatorBuilder
{
    public emailAddress(
        errorMessage?: string | null, 
        summaryMessage?: string | null): IValidatorBuilder;
    public emailAddress(
        validatorParameters: FluentValidatorConfig): IValidatorBuilder;
    public emailAddress(
        arg2?: FluentValidatorConfig | string | null,
        arg3?: string | null): IValidatorBuilder {
        // eslint-disable-next-line @typescript-eslint/no-unused-vars
        let { errorMessage, summaryMessage, conditionConfig, validatorParameters } =
            this.resolveOverloadArgs<EmailAddressConditionConfig>(arg2, arg3);
        let conditionBuilder = this.createConditionBuilder();
        conditionBuilder.emailAddress();
        return this.finish(conditionBuilder,
            errorMessage, summaryMessage, validatorParameters);
    }
}

